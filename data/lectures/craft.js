- 数字の出所・単位・期間を必ず書ける
- メールの件名に会社名・用件・期限を入れられる
- 議事録を決定事項から書き、当日中に出せる
- 資料作成の前に、読み手・目的・枚数を確認できる
- 案件名を社外で口にしない習慣がある
